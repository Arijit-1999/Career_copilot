"""Enums for the Application Tracking and Analytics domain."""

from enum import Enum


class TimelineEventType(str, Enum):
    """Types of timeline events that can occur during an application's lifecycle."""
    STATUS_CHANGED = "STATUS_CHANGED"
    NOTE_ADDED = "NOTE_ADDED"
    RECRUITER_CONTACT = "RECRUITER_CONTACT"
    INTERVIEW_SCHEDULED = "INTERVIEW_SCHEDULED"
    INTERVIEW_COMPLETED = "INTERVIEW_COMPLETED"
    ASSESSMENT_RECEIVED = "ASSESSMENT_RECEIVED"
    ASSESSMENT_SUBMITTED = "ASSESSMENT_SUBMITTED"
    OFFER_RECEIVED = "OFFER_RECEIVED"
    OFFER_NEGOTIATING = "OFFER_NEGOTIATING"
    REJECTION_RECEIVED = "REJECTION_RECEIVED"
    FOLLOW_UP_SENT = "FOLLOW_UP_SENT"
    APPLICATION_WITHDRAWN = "APPLICATION_WITHDRAWN"


class InterviewRoundType(str, Enum):
    """Classifies the type of interview round."""
    RECRUITER_SCREEN = "RECRUITER_SCREEN"
    TECHNICAL_ASSESSMENT = "TECHNICAL_ASSESSMENT"
    TECHNICAL_ROUND_1 = "TECHNICAL_ROUND_1"
    TECHNICAL_ROUND_2 = "TECHNICAL_ROUND_2"
    SYSTEM_DESIGN = "SYSTEM_DESIGN"
    LIVE_CODING = "LIVE_CODING"
    BEHAVIORAL = "BEHAVIORAL"
    HIRING_MANAGER = "HIRING_MANAGER"
    EXECUTIVE_ROUND = "EXECUTIVE_ROUND"
    FINAL_ROUND = "FINAL_ROUND"
    OTHER = "OTHER"


class InterviewFormat(str, Enum):
    """Meeting format for an interview round."""
    VIDEO_CALL = "VIDEO_CALL"
    PHONE_CALL = "PHONE_CALL"
    IN_PERSON = "IN_PERSON"
    ASYNC_ASSESSMENT = "ASYNC_ASSESSMENT"


class InterviewOutcome(str, Enum):
    """Outcome of an interview round."""
    SCHEDULED = "SCHEDULED"
    PASSED = "PASSED"
    FAILED = "FAILED"
    RESCHEDULED = "RESCHEDULED"
    CANCELLED = "CANCELLED"
    AWAITING_FEEDBACK = "AWAITING_FEEDBACK"


class RejectionCategory(str, Enum):
    """Taxonomy of why an application or interview was not successful."""
    SKILLS_GAP = "SKILLS_GAP"
    EXPERIENCE_MISMATCH = "EXPERIENCE_MISMATCH"
    SALARY_MISMATCH = "SALARY_MISMATCH"
